import streamlit as st
import os
import gdown

st.set_page_config(
    page_title="Dashboard Monitoring",
    page_icon="📊",
    layout="wide"
)

FILE_ID = "1v4Y4yEuWpkLKqMR9AJ0wasidM86tUwzD"
VIDEO_PATH = "video_dashboard.mp4"

if not os.path.exists(VIDEO_PATH):
    with st.spinner("Memuat video..."):
        gdown.download(
            f"https://drive.google.com/uc?id={FILE_ID}",
            VIDEO_PATH,
            quiet=False
        )

st.title("Dashboard Monitoring")

if os.path.exists(VIDEO_PATH):

    st.video(
        VIDEO_PATH,
        autoplay=True,
        loop=True,
        muted=True
    )

else:

    st.error("Video gagal dimuat.")

