import os
import gdown

FILE_ID = "1v4Y4yEuWpkLKqMR9AJ0wasidM86tUwzD"
VIDEO_PATH = "/content/video_dashboard.mp4"

if not os.path.exists(VIDEO_PATH):
    print("Sedang download video dari Google Drive...")

    gdown.download(
        f"https://drive.google.com/uc?id={FILE_ID}",
        VIDEO_PATH,
        quiet=False
    )

    print("Download selesai!")
else:
    print("Video sudah ada.")

if os.path.exists(VIDEO_PATH):
    size_mb = os.path.getsize(VIDEO_PATH) / (1024 * 1024)
    print(f"Ukuran video: {size_mb:.2f} MB")
else:
    raise FileNotFoundError("Video gagal didownload dari Google Drive.")

app_code = """
import streamlit as st
import os

st.set_page_config(
    page_title="Dashboard Monitoring",
    page_icon="📊",
    layout="wide"
)

st.title("Dashboard Monitoring")

VIDEO_PATH = "/content/video_dashboard.mp4"

if os.path.exists(VIDEO_PATH):
    st.video(
        VIDEO_PATH,
        autoplay=True,
        loop=True,
        muted=True
    )
else:
    st.error("Video tidak ditemukan.")

st.markdown("---")
st.caption("Dashboard Monitoring")
"""

with open("/content/app.py", "w") as f:
    f.write(app_code)

print("app.py berhasil dibuat.")


